// Renders /tutorials/ (index) and /tutorials/<slug>/ from tools/tutorials-data.js. Called from build-pages.js.
const fs = require('fs');
const path = require('path');
const TUTORIALS = require('./tutorials-data');

// Add one contextual sentence linking each tutorial from its related blog posts (before the FAQs, else at the end)
function injectLinks(posts) {
  for (const tu of TUTORIALS) for (const [slug, sentence] of tu.linkFrom || []) {
    const p = posts.find(x => x.slug === slug);
    if (!p || p.body.includes(`/tutorials/${tu.slug}/`)) continue;
    const para = `<p>${sentence}</p>\n\n`;
    const m = p.body.match(/<h2[^>]*>\s*(?:FAQs?|Frequently asked questions)/i);
    p.body = m ? p.body.slice(0, m.index) + para + p.body.slice(m.index) : p.body.trimEnd() + '\n\n' + para;
  }
}

function build(ctx) {
  const { ROOT, SITE, headCommon, header, footer, contact, waFloat, esc, fmtDate, readMins, plainText, postFaqs, bySlug, WA } = ctx;
  const out = [];
  const body = tu => tu.body(tu.slug).trim();

  const renderTutorial = tu => {
    const url = `${SITE}/tutorials/${tu.slug}/`;
    const svc = bySlug[tu.service];
    const toc = [];
    let html = body(tu).replace(/<h2>(.*?)<\/h2>/g, (m, t) => {
      const id = t.replace(/<[^>]+>/g, '').toLowerCase().replace(/&amp;/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      toc.push([id, t]);
      return `<h2 id="${id}">${t}</h2>`;
    });
    const intro = `<div class="tut-need">
  <p><strong>Time required:</strong> ${esc(tu.time)}</p>
  <p><strong>What you'll need:</strong></p>
  <ul>
${tu.need.map(n => `    <li>${esc(n)}</li>`).join('\n')}
  </ul>
</div>
`;
    const cut = html.indexOf('</p>') + 4;
    html = html.slice(0, cut) + '\n' + intro + html.slice(cut);
    // "Need it done for you?" box before the FAQs
    const help = `<aside class="inline-cta tut-help">
  <strong>Need it done for you?</strong>
  <p>${esc(tu.serviceText)}</p>
  <div>${svc ? `<a href="/${svc.slug}/" class="link-inline">See ${esc(svc.nav)} →</a>` : ''}<a href="#contact" class="link-inline">Get a free quote</a></div>
</aside>

`;
    const fi = html.search(/<h2 id="faqs?"/);
    html = fi > 0 ? html.slice(0, fi) + help + html.slice(fi) : html + '\n' + help;

    const imgs = [...new Set(html.match(/\/assets\/tutorials\/[\w-]+\.svg/g) || [])];
    const faqs = postFaqs(html);
    const steps = toc.filter(([, t]) => /^Step \d+:/.test(t)).map(([id, t], i) => ({ '@type': 'HowToStep', position: i + 1, name: plainText(t).replace(/^Step \d+:\s*/, ''), url: `${url}#${id}` }));
    const schema = {
      '@context': 'https://schema.org',
      '@graph': [
        {
          '@type': 'TechArticle', '@id': `${url}#article`, headline: tu.title, description: tu.description,
          datePublished: tu.date, dateModified: tu.updated || tu.date, mainEntityOfPage: url, inLanguage: 'en-IN',
          image: imgs.map(i => SITE + i),
          author: { '@type': 'Organization', '@id': `${SITE}/#service`, name: 'Samverse', url: `${SITE}/` },
          publisher: { '@type': 'Organization', name: 'Samverse', logo: { '@type': 'ImageObject', url: `${SITE}/assets/icon-512.png` } },
        },
        { '@type': 'HowTo', '@id': `${url}#howto`, name: tu.title, description: tu.description, totalTime: undefined, step: steps },
        {
          '@type': 'BreadcrumbList', itemListElement: [
            { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
            { '@type': 'ListItem', position: 2, name: 'Tutorials', item: `${SITE}/tutorials/` },
            { '@type': 'ListItem', position: 3, name: tu.title, item: url },
          ],
        },
      ],
    };
    if (faqs.length) schema['@graph'].push({ '@type': 'FAQPage', '@id': `${url}#faq`, mainEntity: faqs.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })) });
    const pageTitle = (tu.title + ' | Samverse').length <= 60 ? tu.title + ' | Samverse' : tu.title;
    const waLink = `https://wa.me/${WA}?text=${encodeURIComponent('Hi, I read your tutorial "' + tu.title + '" and need help.')}`;
    const others = TUTORIALS.filter(x => x !== tu);
    const tocList = toc.map(([id, t]) => `              <li><a href="#${id}">${t}</a></li>`).join('\n');

    return `${headCommon(pageTitle, tu.description, url, `  <meta property="og:type" content="article">
  <meta property="article:published_time" content="${tu.date}">
  <script type="application/ld+json">
${JSON.stringify(schema, null, 2)}
  </script>
`)}
<body>

  <!-- Generated by tools/build-pages.js from tools/tutorials-data.js -->
  ${header}

  <div class="read-progress" aria-hidden="true"><span id="readProgress"></span></div>

  <main>
    <article class="post">
      <header class="post-hero">
        <div class="container post-hero-inner">
          <nav class="crumbs" aria-label="Breadcrumb"><a href="/">Home</a> <span>/</span> <a href="/tutorials/">Tutorials</a></nav>
          <a class="post-cat" href="/tutorials/">Tutorial</a>
          <h1>${esc(tu.title)}</h1>
          <p class="post-dek">${esc(tu.description)}</p>
          <div class="post-byline">
            <img src="/assets/logo-mark.svg" alt="" width="44" height="44">
            <div class="post-byline-text">
              <a href="/about/">Samverse</a>
              <span><time datetime="${tu.date}">${fmtDate(tu.date)}</time>${tu.updated ? ` · Updated <time datetime="${tu.updated}">${fmtDate(tu.updated)}</time>` : ''} · ${readMins(html)} min read</span>
            </div>
          </div>
        </div>
      </header>

      <div class="post-layout container">
        <div class="post-body">
          <details class="toc-mobile">
            <summary>On this page</summary>
            <ol>
${tocList}
            </ol>
          </details>
${html}

          <div class="post-cta">
            <h2>Stuck on a step?</h2>
            <p>Tell me where you got stuck and I'll reply with a plan and a fixed quote, usually within 24 hours.</p>
            <div class="hero-cta">
              <a href="#contact" class="btn">Get a Free Quote</a>
              <a href="${waLink}" class="btn btn-ghost" target="_blank" rel="noopener">WhatsApp Me</a>
            </div>
          </div>
        </div>

        <aside class="post-side">
          <nav class="post-toc" aria-label="On this page">
            <strong>On this page</strong>
            <ol>
${tocList}
            </ol>
          </nav>
          <div class="side-cta">
            <strong>Need it done for you?</strong>
            <p>Get a clear plan and a fixed quote, usually within 24 hours.</p>
            <a href="#contact" class="btn btn-sm btn-block">Get a Free Quote</a>
            <a href="${waLink}" class="side-cta-wa" target="_blank" rel="noopener">or chat on WhatsApp</a>
          </div>
        </aside>
      </div>
    </article>

    <section class="section">
      <div class="container">
        <div class="section-head reveal"><span class="eyebrow">Keep learning</span><h2>More tutorials</h2></div>
        <div class="post-grid reveal">
${others.slice(0, 3).map(x => '          ' + card(x)).join('\n')}
        </div>
        <p class="related-all"><a href="/tutorials/" class="link-inline">All tutorials →</a></p>
      </div>
    </section>

    ${contact}
  </main>

  ${footer}

  ${waFloat}

  <script src="/script.js?v=20261112" defer></script>
</body>
</html>
`;
  };

  const card = x => { const im=(body(x).match(/\/assets\/tutorials\/[\w-]+\.svg/)||[])[0]; return `<a class="post-card" href="/tutorials/${x.slug}/">${im?`<img class="post-card-img" src="${im}" alt="${esc(x.title)} step preview" width="1200" height="630" loading="lazy" decoding="async">`:''}<span class="work-tag">Tutorial</span><h3>${esc(x.title)}</h3><p>${esc(x.description)}</p><span class="post-card-meta">${readMins(body(x))} min read</span></a>`; };

  const renderIndex = () => {
    const url = `${SITE}/tutorials/`;
    const schema = {
      '@context': 'https://schema.org',
      '@graph': [
        { '@type': 'CollectionPage', '@id': `${url}#page`, name: 'WordPress, WooCommerce and Shopify Tutorials', url, inLanguage: 'en-IN',
          mainEntity: { '@type': 'ItemList', numberOfItems: TUTORIALS.length, itemListElement: TUTORIALS.map((t, i) => ({ '@type': 'ListItem', position: i + 1, url: `${SITE}/tutorials/${t.slug}/`, name: t.title })) } },
        { '@type': 'BreadcrumbList', itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
          { '@type': 'ListItem', position: 2, name: 'Tutorials', item: url },
        ] },
      ],
    };
    return `${headCommon('WordPress & Shopify Tutorials, Step by Step | Samverse', 'Step-by-step WordPress, WooCommerce and Shopify tutorials with exact menu paths and annotated illustrations: payments, domains, email, Cloudflare and more.', url, `  <meta property="og:type" content="website">
  <script type="application/ld+json">
${JSON.stringify(schema, null, 2)}
  </script>
`)}
<body>

  <!-- Generated by tools/build-pages.js from tools/tutorials-data.js -->
  ${header}

  <main>
    <section class="hero lp-hero">
      <div class="container">
        <nav class="crumbs" aria-label="Breadcrumb"><a href="/">Home</a> <span>/</span> Tutorials</nav>
        <div class="lp-hero-copy">
          <span class="eyebrow">Tutorials</span>
          <h1>WordPress, WooCommerce and Shopify tutorials</h1>
          <p class="lead">Click-by-click guides for common jobs: each one lists what you need, the exact admin path for every step, annotated illustrations, and fixes for what usually goes wrong. For background and decisions, see the <a href="/blog/" class="link-inline">blog</a>.</p>
        </div>
      </div>
    </section>

    <section class="section">
      <div class="container">
        <div class="post-grid">
${TUTORIALS.map(x => '          ' + card(x)).join('\n')}
        </div>
      </div>
    </section>

    ${contact}
  </main>

  ${footer}

  ${waFloat}

  <script src="/script.js?v=20261112" defer></script>
</body>
</html>
`;
  };

  fs.mkdirSync(path.join(ROOT, 'tutorials'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'tutorials', 'index.html'), renderIndex());
  out.push({ loc: `${SITE}/tutorials/`, pr: '0.8' });
  for (const tu of TUTORIALS) {
    const dir = path.join(ROOT, 'tutorials', tu.slug);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), renderTutorial(tu));
    out.push({ loc: `${SITE}/tutorials/${tu.slug}/`, pr: '0.7', lastmod: tu.updated || tu.date, imgs: [...new Set(body(tu).match(/\/assets\/tutorials\/[\w-]+\.svg/g) || [])] });
  }
  console.log('built /tutorials/ +', TUTORIALS.length, 'tutorials');
  return out;
}

module.exports = { injectLinks, build, TUTORIALS };
